import { readFileSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const schemaPath = join(root, 'settings.schema.json')
const outputPath = join(root, '../../windows/src/types/settings.generated.ts')
const manifestPath = join(root, '../rust-core/Cargo.toml')
const generatedSchema = spawnSync('cargo', [
  'run', '--quiet', '--locked', '--manifest-path', manifestPath,
  '--example', 'generate_settings_schema',
], { encoding: 'utf8' })
if (generatedSchema.status !== 0) {
  throw new Error(generatedSchema.stderr || 'Rust Settings schema generation failed')
}
const normalizedSchema = `${generatedSchema.stdout.trim()}\n`
if (process.argv.includes('--check')) {
  const currentSchema = readFileSync(schemaPath, 'utf8').replaceAll('\r\n', '\n')
  if (currentSchema !== normalizedSchema) {
    throw new Error('shared/schema/settings.schema.json is out of date')
  }
} else {
  writeFileSync(schemaPath, normalizedSchema)
}
const schema = JSON.parse(normalizedSchema)

function resolvedDefinition(definition) {
  if (definition.allOf?.length === 1) {
    return resolvedDefinition(definition.allOf[0])
  }
  if (!definition.$ref) return definition
  const prefix = '#/definitions/'
  if (!definition.$ref.startsWith(prefix)) {
    throw new Error(`Unsupported Settings schema reference: ${definition.$ref}`)
  }
  const resolved = schema.definitions?.[definition.$ref.slice(prefix.length)]
  if (!resolved) throw new Error(`Missing Settings schema definition: ${definition.$ref}`)
  return resolved
}

function typescriptType(definition) {
  definition = resolvedDefinition(definition)
  if (Array.isArray(definition.type)) {
    return definition.type.map((type) => typescriptType({ type })).join(' | ')
  }
  if (definition.anyOf) {
    return definition.anyOf.map((option) => typescriptType(option)).join(' | ')
  }
  if (definition.enum) return definition.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (definition.type === 'boolean') return 'boolean'
  if (definition.type === 'integer' || definition.type === 'number') return 'number'
  if (definition.type === 'string') return 'string'
  if (definition.type === 'null') return 'null'
  if (definition.type === 'object' && definition.additionalProperties) {
    return `Record<string, ${typescriptType(definition.additionalProperties)}>`
  }
  throw new Error(`Unsupported Settings schema definition: ${JSON.stringify(definition)}`)
}

const fields = Object.entries(schema.properties)
  .map(([name, definition]) => `  ${name}: ${typescriptType(definition)};`)
  .join('\n')
const generated = `// Generated by shared/schema/generate-settings.mjs. Do not edit.\n\nexport interface SettingsData {\n${fields}\n}\n`

if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n')
  if (current !== generated) {
    throw new Error('windows/src/types/settings.generated.ts is out of date')
  }
} else {
  writeFileSync(outputPath, generated)
}
