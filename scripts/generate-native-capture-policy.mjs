import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = process.argv.includes('--root') ? resolve(process.argv[process.argv.indexOf('--root')+1]) : resolve(dirname(fileURLToPath(import.meta.url)), '..');
const p = JSON.parse(readFileSync(resolve(root, 'shared/schema/native-capture-policy.json'), 'utf8'));
const all = [...p.suppressed,...p.deferred,...p.common.map(v=>v[0]),...p.controls];
if (p.version !== 1 || new Set(all).size !== all.length || all.some(n => typeof n !== 'string' || Buffer.byteLength(n)>256 || /[\x00-\x1f\x7f]/.test(n))) throw new Error('invalid native policy');
if (![p.opaque_limit,...p.common.map(v=>v[1])].every(n=>Number.isSafeInteger(n)&&n>0&&n<=32*1024*1024)) throw new Error('invalid native policy budgets');
const imageFormats = Array.isArray(p.image_formats) ? p.image_formats : null;
if (!imageFormats || imageFormats.length === 0 || imageFormats.some(v => !Array.isArray(v) || v.length !== 2)) throw new Error('invalid native image formats');
const imageNames = imageFormats.map(v=>v[0]);
if (new Set(imageNames).size !== imageNames.length) throw new Error('invalid native image formats');
if (imageFormats.some(([name,mime]) => typeof name !== 'string' || Buffer.byteLength(name)>256 || /[\x00-\x1f\x7f]/.test(name) || typeof mime !== 'string' || Buffer.byteLength(mime)>64 || !/^image\/[a-z0-9.+-]+$/.test(mime)) || imageNames.some(name => !p.common.some(entry=>entry[0]===name))) throw new Error('invalid native image formats');
const cover = p.cover_budget;
if (!cover || !Number.isSafeInteger(cover.frame_limit) || cover.frame_limit<=0 || cover.frame_limit>20 || !Number.isSafeInteger(cover.pixel_limit) || cover.pixel_limit<=0 || cover.pixel_limit>8*1024*1024) throw new Error('invalid native cover budget');
const q = JSON.stringify;
const rawRust = '// Generated by scripts/generate-native-capture-policy.mjs; edit the policy JSON.\n' +
  `pub const OPAQUE_LIMIT: usize = ${p.opaque_limit};\n` +
  `pub const COVER_FRAME_LIMIT: u32 = ${cover.frame_limit};\n` +
  `pub const COVER_PIXEL_LIMIT: u64 = ${cover.pixel_limit};\n` +
  ['suppressed','deferred','controls'].map(k=>`pub const ${k.toUpperCase()}: &[&str] = &[${p[k].map(q).join(',')}];\n`).join('')+
  `pub const COMMON: &[(&str,usize)] = &[${p.common.map(([n,v])=>`(${q(n)},${v})`).join(',')}];\n` +
  `pub const IMAGE_FORMATS: &[(&str,&str)] = &[${imageFormats.map(([name,mime])=>`(${q(name)},${q(mime)})`).join(',')}];\n`;
const formatted = spawnSync('rustfmt', ['--edition','2021','--emit','stdout'], { input:rawRust, encoding:'utf8' });
if (formatted.status !== 0) throw new Error(formatted.stderr);
const rust = formatted.stdout;
const swift = '// BEGIN GENERATED NATIVE POLICY\n// Generated by scripts/generate-native-capture-policy.mjs; edit the policy JSON.\n' +
  `let opaqueLimit = ${p.opaque_limit}\n` +
  ['suppressed','deferred','controls'].map(k=>`let policy${k[0].toUpperCase()+k.slice(1)}: Set<String> = [${p[k].map(q).join(',')}]\n`).join('')+
  `let policyCommon: [String:Int] = [${p.common.map(([n,v])=>`${q(n)}:${v}`).join(',')}]\n` +
  `let policyImageFormats: Set<String> = [${imageNames.map(q).join(',')}]\n` +
  `let policyCoverFrameLimit = ${cover.frame_limit}\n` +
  `let policyCoverPixelLimit = ${cover.pixel_limit}\n// END GENERATED NATIVE POLICY`;
function output(path, text) {
  if (process.argv.includes('--check')) {if(readFileSync(path,'utf8')!==text) throw new Error('stale native policy: '+path);}
  else writeFileSync(path,text);
}
output(resolve(root,'shared/tailsync-protocol/src/native_policy.generated.rs'),rust);
const helper = resolve(root,'macos/src-tauri/clipboard-helper.swift');
const text = readFileSync(helper,'utf8');
if (!text.includes('// BEGIN GENERATED NATIVE POLICY')) throw new Error('missing native policy marker');
output(helper,text.replace(/\/\/ BEGIN GENERATED NATIVE POLICY[\s\S]*?\/\/ END GENERATED NATIVE POLICY/,swift));
console.log('Native capture policy: Rust/Swift in sync');
