func savedAnalysisFrame(kind: UInt8, sourceFormat: String, converter: String,
                        body: String, partial: Bool, truncated: Bool,
                        styleBits: UInt8, tableRows: UInt16, tableCells: UInt16,
                        attachments: [(Int, UInt8, Data)]) -> Data {
    let sourceBytes = Data(sourceFormat.utf8)
    let converterBytes = Data(converter.utf8)
    let bodyBytes = Data(body.utf8)
    var output = Data()
    output.append(contentsOf: Array("RTA1".utf8))
    output.append(1)
    output.append(kind)
    output.append((partial ? 2 : 0) | (truncated ? 1 : 0))
    output.append(styleBits)
    appendBE(UInt16(sourceBytes.count), to: &output)
    appendBE(UInt16(converterBytes.count), to: &output)
    appendBE(UInt32(bodyBytes.count), to: &output)
    appendBE(UInt16(attachments.count), to: &output)
    appendBE(tableRows, to: &output)
    appendBE(tableCells, to: &output)
    output.append(sourceBytes)
    output.append(converterBytes)
    output.append(bodyBytes)
    for (position, state, png) in attachments {
        appendBE(UInt32(position), to: &output)
        output.append(state)
        output.append(0)
        appendBE(UInt32(png.count), to: &output)
        output.append(png)
    }
    return output
}

let styleBold: UInt8 = 1
let styleItalic: UInt8 = 2
let styleUnderline: UInt8 = 4
let styleStrikethrough: UInt8 = 8
let styleUnsupported: UInt8 = 64

func inspectSavedRtf(_ data: Data) -> (UInt16, UInt16)? {
    guard data.count <= (policyCommon["public.rtf"] ?? 0) else { return nil }
    let bytes = [UInt8](data)
    guard bytes.starts(with: Array("{\\rtf1".utf8)) else { return nil }
    var index = 0
    var depth = 0
    var controls = 0
    var rows = 0
    var cells = 0
    while index < bytes.count {
        switch bytes[index] {
        case 123:
            depth += 1
            guard depth <= 64 else { return nil }
            index += 1
        case 125:
            guard depth > 0 else { return nil }
            depth -= 1
            index += 1
        case 92:
            index += 1
            guard index < bytes.count else { return nil }
            if bytes[index] == 39 {
                guard index + 2 < bytes.count else { return nil }
                index += 3
                continue
            }
            if !(65...90).contains(bytes[index]) && !(97...122).contains(bytes[index]) {
                index += 1
                continue
            }
            let start = index
            while index < bytes.count && ((65...90).contains(bytes[index]) || (97...122).contains(bytes[index])) { index += 1 }
            let word = String(bytes: bytes[start..<index], encoding: .ascii) ?? ""
            controls += 1
            guard controls <= 8192 else { return nil }
            var negative = false
            if index < bytes.count && bytes[index] == 45 { negative = true; index += 1 }
            var parameter = 0
            var digits = 0
            while index < bytes.count && (48...57).contains(bytes[index]) {
                digits += 1
                guard digits <= 9 else { return nil }
                parameter = parameter * 10 + Int(bytes[index] - 48)
                index += 1
            }
            if index < bytes.count && bytes[index] == 32 { index += 1 }
            if word == "bin" {
                guard !negative && digits > 0 && parameter <= bytes.count - index else { return nil }
                index += parameter
            } else if word == "trowd" {
                rows += 1
                guard rows <= 2048 else { return nil }
            } else if word == "cell" || word == "nestcell" {
                cells += 1
                guard cells <= 2048 else { return nil }
            }
        default:
            index += 1
        }
    }
    guard depth == 0 else { return nil }
    return (UInt16(rows), UInt16(cells))
}

func savedRtfdRtf(_ data: Data) -> Data? {
    guard let wrapper = FileWrapper(serializedRepresentation: data), wrapper.isDirectory,
          let files = wrapper.fileWrappers, files.count <= policyCoverFrameLimit + 1 else { return nil }
    var rtf: Data?
    var total = 0
    for (name, file) in files {
        guard file.isRegularFile, let bytes = file.regularFileContents,
              bytes.count <= 8 * 1024 * 1024 - total else { return nil }
        total += bytes.count
        if name.lowercased() == "txt.rtf" { rtf = bytes }
    }
    return rtf
}

func savedImagePixels(_ data: Data) -> Int? {
    guard let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary) else { return nil }
    let count = CGImageSourceGetCount(source)
    guard count > 0 && count <= policyCoverFrameLimit else { return nil }
    var total = 0
    for index in 0..<count {
        guard let properties = CGImageSourceCopyPropertiesAtIndex(source, index, nil) as? [CFString: Any],
              let width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
              let height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
              width > 0 && height > 0 else { return nil }
        let (pixels, overflow) = width.multipliedReportingOverflow(by: height)
        guard !overflow && pixels <= policyCoverPixelLimit - total else { return nil }
        total += pixels
    }
    return total
}

func analyzeRichText(_ bytes: Data, rtfd: Bool) -> Data? {
    guard bytes.count <= 8 * 1024 * 1024 else { return nil }
    guard let rtf = rtfd ? savedRtfdRtf(bytes) : bytes,
          let (rows, cells) = inspectSavedRtf(rtf) else { return nil }
    let rich = rtfd
        ? NSAttributedString(rtfd: bytes, documentAttributes: nil)
        : NSAttributedString(rtf: bytes, documentAttributes: nil)
    guard let rich = rich, rich.length <= 1024 * 1024 else { return nil }
    let supported: Set<NSAttributedString.Key> = [
        .attachment, .font, .foregroundColor, .backgroundColor,
        .underlineStyle, .strikethroughStyle, .paragraphStyle,
    ]
    let body = rich.string
    guard body.utf8.count <= savedBodyLimit else { return nil }
    let units = Array(body.utf16)
    var partial = false
    var styleBits: UInt8 = 0
    var attachments: [(Int, UInt8, Data)] = []
    var pixels = 0
    var outputBytes = 0
    var runs = 0
    rich.enumerateAttributes(in: NSRange(location: 0, length: rich.length)) { attributes, range, stop in
        runs += 1
        if runs > 8192 { partial = true; stop.pointee = true; return }
        if !attributes.keys.allSatisfy({ supported.contains($0) }) { partial = true }
        if let font = attributes[.font] as? NSFont {
            let traits = NSFontManager.shared.traits(of: font)
            if traits.contains(.boldFontMask) { styleBits |= styleBold }
            if traits.contains(.italicFontMask) { styleBits |= styleItalic }
        }
        if (attributes[.underlineStyle] as? NSNumber)?.intValue ?? 0 != 0 { styleBits |= styleUnderline }
        if (attributes[.strikethroughStyle] as? NSNumber)?.intValue ?? 0 != 0 { styleBits |= styleStrikethrough }
        if let attachment = attributes[.attachment] as? NSTextAttachment {
            var state: UInt8 = 1
            var png = Data()
            var pixelCost = 0
            if let wrapper = attachment.fileWrapper {
                if wrapper.isRegularFile, let data = wrapper.regularFileContents,
                   let cost = savedImagePixels(data) {
                    if cost <= policyCoverPixelLimit - pixels,
                       let converted = pngFromBitmap(data),
                       converted.count <= savedAttachmentBytesLimit,
                       converted.count <= savedFrameLimit - savedBodyLimit - 65536 - outputBytes {
                        pixelCost = cost
                        state = 0
                        png = converted
                    } else { state = 3; partial = true }
                } else {
                    state = 2
                    partial = true
                }
            }
            for position in range.location..<(range.location + range.length) where units[position] == 0xfffc {
                if attachments.count >= policyCoverFrameLimit {
                    partial = true
                    break
                }
                if state == 0 {
                    if pixelCost > policyCoverPixelLimit - pixels || png.count > savedFrameLimit - savedBodyLimit - 65536 - outputBytes {
                        attachments.append((position, 3, Data()))
                        partial = true
                        continue
                    }
                    pixels += pixelCost
                    outputBytes += png.count
                }
                attachments.append((position, state, png))
            }
        }
    }
    if !attachments.allSatisfy({ $0.2.count <= savedAttachmentBytesLimit }) { return nil }
    if partial { styleBits |= styleUnsupported }
    let frame = savedAnalysisFrame(
        kind: rtfd ? 2 : 1,
        sourceFormat: rtfd ? "com.apple.flat-rtfd" : "public.rtf",
        converter: rtfd ? "tailsync.rtfd-to-facts.v1" : "tailsync.rtf-to-facts.v1",
        body: body, partial: partial, truncated: false,
        styleBits: styleBits, tableRows: rows, tableCells: cells,
        attachments: attachments)
    guard frame.count <= savedFrameLimit else { return nil }
    return frame
}
/// A metadata-only snapshot for a genuine file selection (repair plan §4 R5-01).
/// Every item is a file URL, so there is no composite content to capture. Reporting
/// the shape *before* the item limit is applied is what lets the caller hand a large
/// file copy to the file pipeline; failing the read instead made a 17-file copy
/// invisible to both sync and history.
func fileSelectionSnapshot(before: Int, after: Int, items: Int) -> Data {
    var output = Data("CNS1".utf8)
    output.append(1); output.append(5) // state = FileSelection
    appendBE(UInt16(items), to: &output)
    appendBE(Int64(before), to: &output); appendBE(Int64(after), to: &output)
    // Explicit UInt16: an untyped literal would infer Int (8 bytes) and shift the
    // whole record section, which the decoder rejects as trailing data.
    appendBE(UInt16(0), to: &output) // no format records
    output.append(contentsOf: [0, 0, 0, 0, 0, 0])
    return output
}
func readSnapshotData() -> Data {
    let before = pb.changeCount
    let items = pb.pasteboardItems ?? []
    if isSuppressed(items) { return suppressedData(false, before) }
    // Classify the shape before applying the composite limits: a pure file selection
    // is a different kind of clipboard content, not an oversized composite one.
    if isPureFileSelection(items) {
        let after = pb.changeCount
        return fileSelectionSnapshot(before: before, after: after, items: items.count)
    }
    guard items.count <= 16 else { exit(65) }
    var records = Data(); var count: UInt16 = 0
    func record(_ item: Int, _ type: NSPasteboard.PasteboardType, _ state: UInt8, _ data: Data) {
        let name = Data(type.rawValue.utf8)
        appendBE(UInt16(item), to: &records); records.append(state); records.append(0)
        appendBE(UInt16(name.count), to: &records); records.append(contentsOf: [0, 0])
        appendBE(UInt32(data.count), to: &records); records.append(name); records.append(data); count += 1
    }
    for (index, item) in items.enumerated() {
        let converted = item.data(forType: .rtfd).flatMap(rtfdToPortable)
        for type in allowedTypes where item.types.contains(type) {
            if converted != nil && (type == .html || type == .string) { continue }
            guard count < 64 else { exit(65) }
            guard let bytes = item.data(forType: type) else { record(index, type, 2, Data()); continue }
            let limit: Int = type == .string ? 1024 * 1024 : type == .html ? 2 * 1024 * 1024 : type == .rtf ? 4 * 1024 * 1024 : 32 * 1024 * 1024
            guard bytes.count <= limit, records.count + bytes.count + 300 <= nativeLimit - 32 else { record(index, type, 3, Data()); continue }
            record(index, type, 0, bytes)
            if type == .tiff, !item.types.contains(.png), count < 64 {
                if let png = pngFromBitmap(bytes), records.count + png.count + 300 <= nativeLimit - 32 { record(index, .png, 0, png) }
                else { record(index, .png, 2, Data()) }
            }
        }
        if let converted = converted, count <= 61,
           records.count + converted.html.count + converted.text.count + 900 <= nativeLimit - 32 {
            record(index, .html, 0, converted.html)
            record(index, .string, 0, converted.text)
            record(index, NSPasteboard.PasteboardType("org.tailsync.rtfd-converted"), 0, Data([1]))
        }
    }
    let after = pb.changeCount
    var output = Data("CNS1".utf8)
    output.append(1); output.append(before != after ? 2 : items.isEmpty ? 1 : 0)
    appendBE(UInt16(items.count), to: &output)
    appendBE(Int64(before), to: &output); appendBE(Int64(after), to: &output)
    appendBE(count, to: &output); output.append(contentsOf: [0, 0, 0, 0, 0, 0]); output.append(records)
    return output
}
// CNA1 retains advertised order and read facts. Bounded opaque Data is captured
// without decoding; file/promise dependencies remain unattempted (Absent).
func readArchiveData() -> Data {
    let before = pb.changeCount
    let items = pb.pasteboardItems ?? []
    // Metadata across *all* items precedes every data(forType:) call, including
    // file routing, oversized selections and unknown providers.
    if isSuppressed(items) { return suppressedData(true, before) }
    var originals: [(Int, NSPasteboard.PasteboardType, UInt8, Data)] = []
    var derived: [(Int, String, String, String, Data)] = []
    var complete = true; var used = 32
    let files = isPureFileSelection(items)
    guard items.count <= 16 || files else { exit(65) }
    guard items.count <= Int(UInt16.max) else { exit(65) }
    if !files {
        var metadata: [(Int, NSPasteboard.PasteboardType)] = []
        for (index,item) in items.enumerated() {
            for type in item.types {
                if validNativeName(type.rawValue) { metadata.append((index,type)) }
                else { complete = false }
            }
        }
        func priority(_ name: String) -> Int {
            policyCommon[name] != nil || name == sourceType.rawValue ? 0 : 1
        }
        // Admission and payload reads prefer common formats; the archive still
        // serializes selected descriptors in the OS advertised order.
        let selected = metadata.indices.sorted {
            let a=priority(metadata[$0].1.rawValue), b=priority(metadata[$1].1.rawValue)
            return a == b ? $0 < $1 : a < b
        }.prefix(64).sorted()
        if selected.count != metadata.count { complete = false }
        originals = selected.map { (metadata[$0].0, metadata[$0].1, UInt8(1), Data()) }
        used += originals.reduce(0) { $0 + 12 + $1.1.rawValue.utf8.count }
        let reads = originals.indices.sorted {
            let a=priority(originals[$0].1.rawValue), b=priority(originals[$1].1.rawValue)
            return a == b ? $0 < $1 : a < b
        }
        for slot in reads {
            let name = originals[slot].1.rawValue
            guard let limit = captureLimit(name) else { continue }
            if used >= nativeLimit { originals[slot].2 = 3; continue }
            if let bytes = items[originals[slot].0].data(forType: originals[slot].1) {
                if bytes.count <= limit && bytes.count <= nativeLimit - used {
                    originals[slot].2 = 0; originals[slot].3 = bytes; used += bytes.count
                } else { originals[slot].2 = 3 }
            } else { originals[slot].2 = 2 }
        }
        func addDerived(_ item: Int, _ name: String, _ source: String, _ converter: String, _ bytes: Data) {
            let cost = 12 + name.utf8.count + source.utf8.count + converter.utf8.count + bytes.count
            guard originals.count + derived.count < 64, used + cost <= nativeLimit else { return }
            derived.append((item, name, source, converter, bytes)); used += cost
        }
        for (index, type, state, bytes) in originals where state == 0 {
            if type == .rtfd, let converted = rtfdToPortable(bytes) {
                // Admit this pair atomically; half a conversion is not proof.
                let converter = "tailsync.rtfd-to-portable.v1"
                let cost = 24 + NSPasteboard.PasteboardType.html.rawValue.utf8.count + NSPasteboard.PasteboardType.string.rawValue.utf8.count + 2 * (type.rawValue.utf8.count + converter.utf8.count) + converted.html.count + converted.text.count
                if originals.count + derived.count <= 62, used + cost <= nativeLimit {
                    addDerived(index, NSPasteboard.PasteboardType.html.rawValue, type.rawValue, converter, converted.html)
                    addDerived(index, NSPasteboard.PasteboardType.string.rawValue, type.rawValue, converter, converted.text)
                }
            }
            if type == .tiff, !originals.contains(where: { $0.0 == index && $0.1 == .png && $0.2 == 0 }), let png = pngFromBitmap(bytes) {
                addDerived(index, NSPasteboard.PasteboardType.png.rawValue, type.rawValue, "tailsync.tiff-to-png.v1", png)
            }
            // O03: an original encoding the portable model cannot carry gets an
            // explicit bounded static cover. The original stays in `originals`
            // and is what native replay publishes; the cover is only the
            // compatibility representation for PNG consumers.
            let originalName = type.rawValue
            if policyImageFormats.contains(originalName),
               !(originalName == "public.png" && isStaticPng(bytes)),
               !derived.contains(where: { $0.0 == index && $0.1 == NSPasteboard.PasteboardType.png.rawValue }),
               let cover = staticCover(bytes) {
                addDerived(index, NSPasteboard.PasteboardType.png.rawValue, originalName, "tailsync.image-static-cover.v1", cover)
            }
        }
    }
    derived.removeAll { d in
        d.1 == NSPasteboard.PasteboardType.png.rawValue && originals.contains { o in
            o.0 == d.0 && o.1 == .png && o.2 == 0 && isStaticPng(o.3)
        }
    }
    // QQ's complete element sequence describes one message. Additional items
    // are file descriptors for that sequence, not independent text documents.
    if !files, complete, let source = originals.first(where: {
        $0.0 == 0 && $0.1.rawValue == qqMessageType && $0.2 == 0
    }), originals.filter({ $0.0 > 0 }).allSatisfy({ $0.1 == .fileURL }),
       let converted = qqToPortable(source.3, itemCount: items.count,
           fallbackPNG: derived.first(where: { $0.0 == 0 && $0.1 == "public.png" })?.4
               ?? originals.first(where: { $0.0 == 0 && $0.1 == .png && $0.2 == 0 })?.3) {
        QQImageCacheAccess().rememberSuggestion(from: source.3)
        let pair = [("public.html", converted.html), ("public.utf8-plain-text", converted.text)]
        let cost = pair.reduce(0) { $0 + 12 + $1.0.utf8.count + qqMessageType.utf8.count + qqConverter.utf8.count + $1.1.count }
        if originals.count + derived.count + 2 <= 64, used + cost <= nativeLimit {
            for (name, bytes) in pair {
                derived.append((0, name, qqMessageType, qqConverter, bytes))
            }
            used += cost
        }
    }
    let after = pb.changeCount
    let state: UInt8 = before != after ? 2 : files ? 5 : items.isEmpty ? 1 : 0
    if state != 0 { derived.removeAll() }
    var output = Data("CNA1".utf8)
    output.append(1); output.append(state); output.append(1); output.append(complete ? 1 : 0)
    appendBE(Int64(before), to: &output); appendBE(Int64(after), to: &output)
    appendBE(UInt16(items.count), to: &output); appendBE(UInt16(originals.count), to: &output); appendBE(UInt16(derived.count), to: &output); output.append(contentsOf: [0, 0])
    for (item, type, status, data) in originals {
        let name = Data(type.rawValue.utf8)
        appendBE(UInt16(item), to: &output); output.append(status); output.append(0)
        appendBE(UInt16(name.count), to: &output); output.append(contentsOf: [0, 0]); appendBE(UInt32(data.count), to: &output)
        output.append(name); output.append(data)
    }
    for (item, name, source, converter, bytes) in derived {
        appendBE(UInt16(item), to: &output)
        for string in [name, source, converter] { appendBE(UInt16(string.utf8.count), to: &output) }
        appendBE(UInt32(bytes.count), to: &output)
        for string in [name, source, converter] { output.append(Data(string.utf8)) }
        output.append(bytes)
    }
    guard output.count <= nativeLimit else { exit(65) }
    return output
}
