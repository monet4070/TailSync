/// One account's image cache; neither messages nor arbitrary file URLs are admitted.
struct QQImageCachePath {
    static let prefix = ["Library", "Containers", "com.tencent.qq", "Data", "Library", "Application Support", "QQ"]
    let root: String
    let relative: [String]

    static func cacheRoot(_ path: String, home: String) -> Bool {
        let prefix = home + "/" + Self.prefix.joined(separator: "/") + "/"
        guard path.hasPrefix(prefix) else { return false }
        let pieces = String(path.dropFirst(prefix.count)).split(separator: "/", omittingEmptySubsequences: false)
        return pieces.count == 3 && pieces[0].range(of: "\\Ant_qq_[a-fA-F0-9]+\\z", options: .regularExpression) != nil
            && pieces[1] == "nt_data" && pieces[2] == "Pic"
    }

    init?(_ path: String, home: String) {
        let pieces = path.split(separator: "/", omittingEmptySubsequences: false).map(String.init)
        guard pieces.count >= 4 else { return nil }
        let root = pieces.dropLast(3).joined(separator: "/")
        let relative = Array(pieces.suffix(3))
        guard Self.cacheRoot(root, home: home),
              relative[0].range(of: "\\A[0-9]{4}-[0-9]{2}\\z", options: .regularExpression) != nil,
              relative[1] == "Ori",
              relative[2].range(of: "\\A[a-fA-F0-9]{32}\\.(png|jpe?g|webp|tiff?|gif)\\z", options: [.regularExpression, .caseInsensitive]) != nil
        else { return nil }
        self.root = root; self.relative = relative
    }
}

