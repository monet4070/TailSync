struct QQImageCacheAccess {
    let home: String
    let bookmarkURL: URL
    init(home: String = FileManager.default.homeDirectoryForCurrentUser.path, bookmarkURL: URL? = nil) {
        self.home = home
        self.bookmarkURL = bookmarkURL ?? Self.configurationURL(
            environment: ProcessInfo.processInfo.environment,
            applicationSupport: FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0])
    }
    static func configurationURL(environment: [String: String], applicationSupport: URL) -> URL {
        let root = environment["TAILSYNC_DATA_DIR"].map { URL(fileURLWithPath: $0, isDirectory: true) }
            ?? applicationSupport.appendingPathComponent("com.tailsync.TailSync", isDirectory: true)
        return root.appendingPathComponent("qq-image-cache.bookmark")
    }

    private func canonicalDirectory(_ path: String) -> Bool {
        guard let resolved = realpath(path, nil) else { return false }
        defer { free(resolved) }
        // Reject symlinks anywhere in the selected QQ subtree. System aliases
        // above the user's home (e.g. /var -> /private/var in tests) are allowed.
        guard let canonicalHome = realpath(home, nil) else { return false }
        defer { free(canonicalHome) }
        return String(cString: resolved) == String(cString: canonicalHome) + String(path.dropFirst(home.count))
    }

    private func resolve(_ data: Data, expectedRoot: String? = nil) -> QQScopedDirectory? {
        var stale = false
        guard data.count <= 64 * 1024,
              let url = try? URL(resolvingBookmarkData: data, options: [.withSecurityScope, .withoutUI, .withoutMounting],
                                 relativeTo: nil, bookmarkDataIsStale: &stale),
              !stale, url.isFileURL, QQImageCachePath.cacheRoot(url.path, home: home),
              expectedRoot == nil || url.path == expectedRoot else { return nil }
        let scope = QQScopedDirectory(url)
        guard canonicalDirectory(url.path) else { return nil }
        let fd = open(url.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard fd >= 0 else { return nil }
        defer { close(fd) }
        var info = stat()
        guard fstat(fd, &info) == 0, info.st_uid == getuid() else { return nil }
        return scope
    }

    func authorizedDirectory(for root: String? = nil) -> QQScopedDirectory? {
        guard let data = boundedFile(bookmarkURL.path, limit: 64 * 1024) else { return nil }
        return resolve(data, expectedRoot: root)
    }
    func status() -> String { authorizedDirectory() == nil ? "not_authorized" : "authorized" }

    private var suggestionURL: URL { bookmarkURL.appendingPathExtension("suggestion") }

    /// Remember only a bounded directory hint from the copied message. This
    /// neither enumerates QQ accounts nor grants access to any directory.
    func messageDirectory(from bytes: Data) -> URL? {
        guard bytes.count <= 1024 * 1024,
              let rows = (try? PropertyListSerialization.propertyList(from: bytes, options: [], format: nil)) as? [[String: Any]],
              !rows.isEmpty, rows.count <= 256 else { return nil }
        var roots = Set<String>()
        for row in rows {
            guard Set(row.keys) == ["TencentElementType", "TencentElementValue"],
                  let type = row["TencentElementType"] as? NSNumber,
                  CFGetTypeID(type) != CFBooleanGetTypeID(),
                  type.doubleValue == Double(type.intValue), [1, 11].contains(type.intValue),
                  let value = row["TencentElementValue"] as? String else { return nil }
            if type.intValue == 1 {
                guard let image = QQImageCachePath(value, home: home) else { return nil }
                roots.insert(image.root)
            }
        }
        guard roots.count == 1, let root = roots.first, root.utf8.count <= 4096 else { return nil }
        return URL(fileURLWithPath: root, isDirectory: true)
    }

    @discardableResult
    func rememberSuggestion(from bytes: Data) -> Bool {
        guard let directory = messageDirectory(from: bytes) else { return false }
        do { try savePrivate(Data(directory.path.utf8), to: suggestionURL); return true }
        catch { return false }
    }

    func suggestedDirectory() -> URL? {
        if let bytes = boundedFile(suggestionURL.path, limit: 4096),
           let root = String(data: bytes, encoding: .utf8), QQImageCachePath.cacheRoot(root, home: home) {
            return URL(fileURLWithPath: root, isDirectory: true)
        }
        return authorizedDirectory()?.url
    }

    func revoke() throws {
        let parent = bookmarkURL.deletingLastPathComponent()
        let directory = open(parent.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        if directory < 0, errno == ENOENT { return }
        guard directory >= 0 else { throw CocoaError(.fileWriteNoPermission) }
        defer { close(directory) }
        var info = stat()
        guard fstat(directory, &info) == 0, info.st_uid == getuid() else { throw CocoaError(.fileWriteNoPermission) }
        guard unlinkat(directory, bookmarkURL.lastPathComponent, 0) == 0 || errno == ENOENT else {
            throw CocoaError(.fileWriteNoPermission)
        }
    }

    /// Called only after the user accepts the folder picker, never by capture.
    func remember(_ url: URL) throws {
        guard url.isFileURL, QQImageCachePath.cacheRoot(url.path, home: home) else {
            throw CocoaError(.fileReadInvalidFileName)
        }
        let selectedScope = QQScopedDirectory(url)
        defer { withExtendedLifetime(selectedScope) {} }
        guard canonicalDirectory(url.path) else { throw CocoaError(.fileReadInvalidFileName) }
        let data = try url.bookmarkData(options: [.withSecurityScope, .securityScopeAllowOnlyReadAccess],
                                       includingResourceValuesForKeys: nil, relativeTo: nil)
        guard let check = resolve(data, expectedRoot: url.path) else { throw CocoaError(.fileReadNoPermission) }
        defer { withExtendedLifetime(check) {} }
        try savePrivate(data, to: bookmarkURL)
    }

    private func savePrivate(_ data: Data, to destination: URL) throws {
        let parent = destination.deletingLastPathComponent()
        try FileManager.default.createDirectory(at: parent, withIntermediateDirectories: true,
                                               attributes: [.posixPermissions: 0o700])
        let directory = open(parent.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard directory >= 0 else { throw CocoaError(.fileWriteNoPermission) }
        defer { close(directory) }
        var info = stat()
        guard fstat(directory, &info) == 0, info.st_uid == getuid() else { throw CocoaError(.fileWriteNoPermission) }
        let temporary = ".qq-image-cache-\(UUID().uuidString).tmp"
        let fd = openat(directory, temporary, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC, 0o600)
        guard fd >= 0 else { throw CocoaError(.fileWriteNoPermission) }
        defer { close(fd); unlinkat(directory, temporary, 0) }
        let written = data.withUnsafeBytes { Darwin.write(fd, $0.baseAddress, $0.count) }
        guard written == data.count, fsync(fd) == 0,
              renameat(directory, temporary, directory, destination.lastPathComponent) == 0
        else { throw CocoaError(.fileWriteUnknown) }
    }

    private func boundedFile(_ path: String, limit: Int) -> Data? {
        let fd = open(path, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
        guard fd >= 0 else { return nil }
        defer { close(fd) }
        return boundedFile(fd, limit: limit)
    }
    private func boundedFile(_ fd: Int32, limit: Int) -> Data? {
        var before = stat()
        guard fstat(fd, &before) == 0, before.st_mode & S_IFMT == S_IFREG,
              before.st_uid == getuid(), before.st_size > 0, before.st_size <= limit else { return nil }
        var data = Data(); var buffer = [UInt8](repeating: 0, count: min(64 * 1024, limit + 1))
        while data.count <= limit {
            let count = Darwin.read(fd, &buffer, min(buffer.count, limit + 1 - data.count))
            if count == 0 { break }
            if count < 0 && errno == EINTR { continue }
            guard count > 0 else { return nil }
            data.append(contentsOf: buffer.prefix(count))
        }
        var after = stat()
        guard data.count == before.st_size, fstat(fd, &after) == 0, before.st_size == after.st_size,
              before.st_mtimespec.tv_sec == after.st_mtimespec.tv_sec,
              before.st_mtimespec.tv_nsec == after.st_mtimespec.tv_nsec else { return nil }
        return data
    }

    func read(_ path: String) -> Data? {
        guard let image = QQImageCachePath(path, home: home),
              let scope = authorizedDirectory(for: image.root) else { return nil }
        defer { withExtendedLifetime(scope) {} }
        // A disabled setting must not read even caches that happen to be readable
        // without a security-scoped bookmark (for example under broader OS grants).
        var directory = open(scope.url.path, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
        guard directory >= 0 else { return nil }
        defer { close(directory) }
        for piece in image.relative.dropLast() {
            let next = openat(directory, piece, O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC)
            guard next >= 0 else { return nil }
            close(directory); directory = next
        }
        let fd = openat(directory, image.relative.last!, O_RDONLY | O_NOFOLLOW | O_NONBLOCK | O_CLOEXEC)
        guard fd >= 0 else { return nil }
        defer { close(fd) }
        return boundedFile(fd, limit: 4 * 1024 * 1024)
    }
}
