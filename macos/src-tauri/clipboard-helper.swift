func imageWithinBudget(_ bytes: Data) -> Bool {
    guard let source=CGImageSourceCreateWithData(bytes as CFData, [kCGImageSourceShouldCache:false] as CFDictionary) else { return false }
    let count=CGImageSourceGetCount(source)
    guard count>0, count<=policyCoverFrameLimit else { return false }
    var total=0
    for index in 0..<count {
        guard let properties=CGImageSourceCopyPropertiesAtIndex(source,index,nil) as? [CFString:Any],
              let width=(properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
              let height=(properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
              width>0, height>0 else { return false }
        let (pixels,overflow)=width.multipliedReportingOverflow(by:height)
        guard !overflow, pixels<=policyCoverPixelLimit-total else { return false }
        total+=pixels
    }
    return true
}
func pngFromBitmap(_ bytes: Data) -> Data? {
    guard let source = CGImageSourceCreateWithData(bytes as CFData, [kCGImageSourceShouldCache:false] as CFDictionary),
          CGImageSourceGetCount(source) == 1 else { return nil }
    return staticCover(bytes)
}
/// True when the bytes are already the single-frame PNG the portable model
/// carries, so no cover is needed.
func isStaticPng(_ bytes: Data) -> Bool {
    let header = [UInt8](bytes.prefix(4 * 1024 * 1024))
    guard header.count >= 33, Array(header.prefix(8)) == [137,80,78,71,13,10,26,10] else { return false }
    var offset = 8
    while offset + 8 <= header.count {
        let length = header[offset..<offset+4].reduce(0) { ($0 << 8) | Int($1) }
        let end = offset + 12 + length
        guard end <= bytes.count else { return false }
        let kind = Array(header[offset+4..<offset+8])
        // A one-frame APNG is still an APNG container and needs a cover.
        if kind == Array("acTL".utf8) { return false }
        if kind == Array("IDAT".utf8) { return true }
        if kind == Array("IEND".utf8) { return false }
        offset = end
    }
    return false
}
/// Bounded static cover for an original encoding the portable model cannot
/// carry (APNG/GIF/WebP/multi-page TIFF). Frame 0 is rendered explicitly and the
/// original bytes are never touched. `imageWithinBudget` is the cumulative
/// frame and pixel admission for the whole animation, so a large animation is
/// retained as an original without a cover rather than decoded here.
func staticCover(_ bytes: Data) -> Data? {
    guard imageWithinBudget(bytes),
          let source=CGImageSourceCreateWithData(bytes as CFData,[kCGImageSourceShouldCache:false] as CFDictionary),
          CGImageSourceGetCount(source) >= 1,
          let image=CGImageSourceCreateImageAtIndex(source,0,[kCGImageSourceShouldCache:false] as CFDictionary) else { return nil }
    let bitmap = NSBitmapImageRep(cgImage: image)
    guard bitmap.pixelsWide > 0, bitmap.pixelsHigh > 0 else { return nil }
    let (pixels, overflow) = bitmap.pixelsWide.multipliedReportingOverflow(by: bitmap.pixelsHigh)
    guard !overflow, pixels <= policyCoverPixelLimit else { return nil }
    return bitmap.representation(using: .png, properties: [:])
}
