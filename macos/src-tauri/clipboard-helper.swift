func qqToPortable(_ bytes: Data, itemCount: Int, fallbackPNG: Data? = nil,
                  loadImage: (String) -> Data? = readQQAttachment) -> (html: Data, text: Data, missing: Int)? {
    guard bytes.count <= 1024 * 1024,
          let rows = (try? PropertyListSerialization.propertyList(from: bytes, options: [], format: nil)) as? [[String: Any]],
          !rows.isEmpty, rows.count <= 256 else { return nil }
    var elements: [(Int, String)] = []; var textBytes = 0
    for row in rows {
        guard Set(row.keys) == ["TencentElementType", "TencentElementValue"],
              let type = row["TencentElementType"] as? NSNumber,
              CFGetTypeID(type) != CFBooleanGetTypeID(),
              type.doubleValue == Double(type.intValue), [1, 11].contains(type.intValue),
              let value = row["TencentElementValue"] as? String
        else { return nil }
        textBytes += value.utf8.count
        guard textBytes <= 1024 * 1024 else { return nil }
        elements.append((type.intValue, value))
    }
    let count = elements.filter { $0.0 == 1 }.count
    guard count <= 8, (count == itemCount || (count == 0 && itemCount == 1)) else { return nil }
    func escape(_ value: String) -> String {
        value.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
            .replacingOccurrences(of: "\n", with: "<br>")
    }
    var html = "<meta charset='utf-8'>"; var text = ""; var index = 0; var missing = 0; var pixels: UInt64 = 0
    let deadline = Date().addingTimeInterval(3)
    for (type, value) in elements {
        guard Date() < deadline else { return nil }
        if type == 11 {
            text += value; html += "<span>\(escape(value))</span>"; continue
        }
        let source = loadImage(value) ?? (index == 0 ? fallbackPNG : nil)
        var png: Data?
        if let source, source.count <= 4 * 1024 * 1024,
           let image = CGImageSourceCreateWithData(source as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
           CGImageSourceGetCount(image) == 1,
           !(Array(source.prefix(8)) == [137,80,78,71,13,10,26,10] && !isStaticPng(source)),
           let decoded = staticCover(source),
           let width = readBE(decoded, 16, 4), let height = readBE(decoded, 20, 4),
           width > 0, height > 0, width * height <= UInt64(policyCoverPixelLimit),
           pixels + width * height <= 8 * 1024 * 1024,
           html.utf8.count + decoded.count * 4 / 3 + textBytes + 1024 < 2 * 1024 * 1024 {
            png = decoded; pixels += width * height
        }
        if let png {
            html += "<img src='data:image/png;base64,\(png.base64EncodedString())'>"
        } else {
            // Keep the image's position without leaking the source cache path.
            html += "<img src='qq-missing-image:\(index)' alt='QQ image \(index + 1)'>"; missing += 1
        }
        index += 1
    }
    guard html.utf8.count <= 2 * 1024 * 1024, text.utf8.count <= 1024 * 1024 else { return nil }
    // An image-only message still needs the atomic conversion pair.
    if text.isEmpty { text = "QQ image × \(count)" }
    return (Data(html.utf8), Data(text.utf8), missing)
}

/// RTFD attachments are converted inside this deadline-controlled helper. Only
/// embedded regular-file images are read; no URL or filesystem resolver is used.
func rtfdToPortable(_ bytes: Data) -> (html: Data, text: Data)? {
    guard bytes.count <= 8 * 1024 * 1024,
          let rich = NSAttributedString(rtfd: bytes, documentAttributes: nil),
          rich.length <= 1024 * 1024 else { return nil }
    func escaped(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;").replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;").replacingOccurrences(of: "\n", with: "<br>")
    }
    var html = "<div>"; var valid = true; var pixels = 0; var images = 0; var htmlBytes = 5
    func append(_ fragment: String) {
        let size = fragment.utf8.count
        guard size <= 2 * 1024 * 1024 - htmlBytes else { valid = false; return }
        html += fragment; htmlBytes += size
    }
    func colour(_ value: Any?) -> String? {
        guard let colour = value as? NSColor, let rgb = colour.usingColorSpace(.deviceRGB) else { return nil }
        return "rgba(\(Int(rgb.redComponent * 255)),\(Int(rgb.greenComponent * 255)),\(Int(rgb.blueComponent * 255)),\(rgb.alphaComponent))"
    }
    rich.enumerateAttributes(in: NSRange(location: 0, length: rich.length)) { attributes, range, stop in
        // WebKit includes kerning and stroke metadata even on ordinary text.
        // These cosmetic attributes may be simplified without dropping the
        // body or its attachments. Unknown semantic attributes remain guarded.
        let supported: Set<NSAttributedString.Key> = [.attachment, .font, .foregroundColor, .backgroundColor, .underlineStyle, .strikethroughStyle, .paragraphStyle, .kern, .strokeColor, .strokeWidth]
        guard attributes.keys.allSatisfy({ supported.contains($0) }) else { valid = false; stop.pointee = true; return }
        if let paragraph = attributes[.paragraphStyle] as? NSParagraphStyle,
           paragraph.alignment != .natural && paragraph.alignment != .left ||
           (attributes[.paragraphStyle] as? NSParagraphStyle).map({ $0.firstLineHeadIndent != 0 || $0.headIndent != 0 || $0.tailIndent != 0 || $0.lineSpacing != 0 || $0.paragraphSpacing != 0 }) == true {
            valid = false; stop.pointee = true; return
        }
        if let attachment = attributes[.attachment] as? NSTextAttachment {
            guard let wrapper = attachment.fileWrapper, wrapper.isRegularFile,
                  let data = wrapper.regularFileContents, imageWithinBudget(data),
                  let source = CGImageSourceCreateWithData(data as CFData, nil),
                  let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
                  let height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
                  width * height <= policyCoverPixelLimit - pixels, images < policyCoverFrameLimit,
                  let png = pngFromBitmap(data) else { valid = false; stop.pointee = true; return }
            pixels += width * height; images += 1
            append("<img src=\"data:image/png;base64,\(png.base64EncodedString())\">")
        } else {
            var styles: [String] = []
            if let font = attributes[.font] as? NSFont {
                let traits = NSFontManager.shared.traits(of: font)
                if traits.contains(.boldFontMask) { styles.append("font-weight:bold") }
                if traits.contains(.italicFontMask) { styles.append("font-style:italic") }
                if let family = font.familyName { styles.append("font-family:\(family)") }
                styles.append("font-size:\(min(200, max(1, font.pointSize)))pt")
            }
            if (attributes[.underlineStyle] as? NSNumber)?.intValue ?? 0 != 0 { styles.append("text-decoration:underline") }
            if (attributes[.strikethroughStyle] as? NSNumber)?.intValue ?? 0 != 0 { styles.append("text-decoration:line-through") }
            if let value = colour(attributes[.foregroundColor]) { styles.append("color:\(value)") }
            if let value = colour(attributes[.backgroundColor]) { styles.append("background-color:\(value)") }
            let text = (rich.string as NSString).substring(with: range)
            append("<span style=\"\(escaped(styles.joined(separator: ";")))\">\(escaped(text))</span>")
        }
        if !valid { stop.pointee = true }
    }
    append("</div>")
    let plain = Data(rich.string.replacingOccurrences(of: "\u{fffc}", with: "").utf8)
    guard valid, html.utf8.count <= 2 * 1024 * 1024, plain.count <= 1024 * 1024 else { return nil }
    return (Data(html.utf8), plain)
}

let savedBodyLimit = 1024 * 1024
let savedAttachmentLimit = 64
