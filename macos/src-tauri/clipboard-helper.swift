func appendBE<T: FixedWidthInteger>(_ value: T, to data: inout Data) {
    var value = value.bigEndian
    withUnsafeBytes(of: &value) { data.append(contentsOf: $0) }
}
func readBE(_ data: Data, _ offset: Int, _ count: Int) -> UInt64? {
    guard offset >= 0, count > 0, count <= 8, offset <= data.count - count else { return nil }
    return data[offset..<offset + count].reduce(0) { ($0 << 8) | UInt64($1) }
}
func validNativeName(_ name: String) -> Bool {
